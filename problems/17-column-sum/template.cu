__global__ void colsum(const float* x, float* out, int rows, int cols) {
    // 先照抄最自然的写法,看看它有多慢(这也是性能基线的写法):
    //
    //     int j = blockIdx.x * blockDim.x + threadIdx.x;
    //     if (j >= cols) return;
    //     float acc = 0;
    //     for (int i = 0; i < rows; ++i) acc += x[(long)i * cols + j];
    //     out[j] = acc;
    //
    // 它是**正确**的,访存也是**完全合并**的(warp 里相邻 lane 读相邻的列,
    // 一条 load 正好覆盖 128 个连续字节)。但它慢得离谱,而原因不在访存:
    //
    // ★ 这道题的全部物理在这儿:
    //   **它的线程数 = cols。** big 用例 cols = 512 ⇒ 2 个 256 线程的块
    //   ⇒ 16 个 warp,而这张卡有 8192 个 warp 槽位。实测 9% 峰值。
    //   每个线程还要串行做 131072 次"load + 加",一条流水线掩不住这个延迟。
    //
    //   数据有 6710 万个元素那么多,但"工作"只被切成了 512 份。
    //   **并行度从来不是由"数据量"决定的,是由"你怎么切"决定的。**
    //
    // 你要做的是把"在飞的东西"变多。它在飞多少,大致是三个因子的乘积:
    //
    //     块数 × 每块 warp 数 × 每 warp 在飞的访存条数
    //
    // 三个因子你都能拧。但注意:**块数这一维有个硬上限** ——
    // 只要一个块负责"一段列、自己扫完所有行",块数就只能是
    // ceil(cols/32) = 16(big 用例)。把块加胖(256 → 1024 线程)能拧第二个
    // 因子,实测能到 72%,但 128 个 SM 里剩下 112 个还是闲的。
    // **想让块数本身变多,只有把 rows 也切开。**
    //
    // 路 A(不用合并):
    //   一个 block 负责"一小段列 × 全部行",块内再按行分组
    //   (比如 block = (tx=32, ty=8):tx 是块内的列,ty 是块内的行并行度),
    //   每组的线程各自沿行累加,最后在块内把这 8 个部分和加起来。
    //   一列完整地属于一个 block ⇒ 块与块之间**不需要**任何合并。
    //
    // 路 B(想上 S 就得走这条):把行切成 max_chunks 段,blockIdx.y 是段号,
    //   块间用下面两种方式之一合并:
    //     * atomicAdd(&out[j], v):最省事。⚠️ out 每轮开始前是**毒值**,
    //       你必须在 launcher 里先清零(cudaMemsetAsync,用 ctx.stream),
    //       这一趟也要记账。这里**没有** 16 题那种"一个 warp 的 32 个 lane
    //       抢同一个地址"的争用 —— 32 个 lane 加的是 32 个不同的列。
    //     * partial + 第二个 kernel:每个 (段, 列) 写一个部分和,第二个 kernel
    //       把它们加起来。没有争用、顺序确定 —— 参考解走这条。
    //   ⚠️ 第二条路的账要算清楚:partial 的流量是 2*segs*cols*4 字节,
    //      占比 2*segs/rows;而且第二个 kernel 只有 cols 个工作项
    //      (并行度又掉回"输出少"那一侧了),它必须靠"数据量小"来便宜,
    //      不能靠并行度。
    //   ⚠️ 块内按列归约要跨 ty 求和:共享内存 + __syncthreads。少一个就是
    //      "有时对有时错",跑一次抓不住(repeat=3 + racecheck 抓得住)。

