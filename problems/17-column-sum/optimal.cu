// 值得亲手验证的五件事:
//
// 1. **路 A:干脆不合并,让一个 block 包下一整列,然后把它加胖。**
//    grid = (ceil(cols/32), 1),块内归约完直接写 out,不用 partial。
//      (32,4)=128 线程 → 12% ;(32,8)=256 → 23% ;(32,16)=512 → 41% ;
//      (32,32)=1024 → 72%
//    **同一个算法、同样 16 个块,6 倍的差距只来自"块里塞了多少 warp"。**
//    但 72% 就是头了:块数(16)改不了,块大小(1024)也用满了。
//
// 2. **把 segs 从 1 扫到 max_chunks。** 实测:
//        22%(1) → 42%(2) → 71%(4) → 91%(8) → 94%(16) → 93%(32) → 91%(≥64)
//    上升段卡在"有多少个块在跑",256 个块以后走平。**拐点在"每个 SM 至少
//    一个块"附近** —— 64 到 128 个块之间是个台阶(71% → 91%),不是斜坡。
//
// 3. **把 lane→数据的映射换一下:让同一个 warp 的 32 个 lane 去读同一列的
//    32 个不同行**(而不是相邻的 32 列)。语义一个字都不用改,只是 tx 和 ty
//    的角色对调。实测(按块数对照):
//        块数      128     256     512    1024    2048
//        合并      91%     94%     93%     91%     91%
//        散读      84%     70%     60%     36%     41%
//    **注意散读那一行:块数小的时候它看着还行(84%),块数一上来就崩。**
//    这是"低并行度掩盖散读"的活样本 —— 卡没填满时,多出来的 L1/L2 事务
//    不要钱。所以"我改成散读之后分数没掉"不能证明散读没问题,
//    只能证明**你还没撞到墙**。
//
// 4. **块形状换成 (32,16)、(64,4)、(16,8)。**
//    (16,8) 会让一个 warp 横跨两行 ty —— 两边都不再是 128 字节的整段,
//    一条 load 会拆成两个 64 字节的请求。它不一定吃亏(总字节数没变),
//    但它是"线程映射 vs 访存粒度"的活教材。
//
// 5. **atomicAdd 路线**(记得在 launcher 里 cudaMemsetAsync 清零 out):
//    实测 0.287 ms / 936 GB/s / 93%,和两阶段一个水平。这里**没有** 16 题
//    那种同一地址的争用 —— 一个 warp 的 32 个 lane 加的是 32 个不同的地址,
//    同一个地址只会被 segs 个块先后各加一次。所以"原子操作慢"这句话是
//    不成立的:慢的永远是**同一个地址被轮着访问**,而不是"原子"这两个字。
//    (代价:这条路要付 memset 一趟的钱,partial 那条路不用。)
