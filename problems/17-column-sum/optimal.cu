// 题目 17 的参考解
//
// 这题的核心一句话:
//   **数据有 6710 万个元素,但"工作被切成了几份"是由你决定的 ——
//     按输出切只有 cols = 512 份,而块数又被 ceil(cols/32) = 16 钉死;
//     把行也切一刀,块数才上得去。**
//
// 参考解走"两阶段":先分段算部分和,再用第二个 kernel 合并。
//
//   阶段一:block = (32, 8) = 256 线程;grid = (ceil(cols/32), segs)。
//           threadIdx.x 是块内的列(⇒ 相邻 lane 读相邻地址,一条 load 正好
//           128 个连续字节),threadIdx.y 是块内的行并行度(8 个线程分摊同一
//           列的行),blockIdx.y 是行分段。每个线程沿行累加,块内用共享内存
//           按列把 8 个部分和加起来,每 (段, 列) 写一个 partial。
//   阶段二:一个线程负责一列,把 segs 个部分和顺序加起来。
//
// 为什么不用 atomicAdd:两条路都能拿到 S(实测都在 93% 上下),但 partial 这条
// 路的加法顺序是固定的,而且不需要先 memset 一遍 out —— 少一笔账。
//
// ---------------------------------------------------------------------------
// 实测(4090,框架自动清 L2,big 用例 rows=131072 cols=512,268MB 流量)。
// ⚠️ 下面这批是**同一次运行里**测的:这是张共享卡,L2 被邻居占着的时候
//    跨次比较会漂 ±3~5%,只有同批测量才谈得上"可比"。
//
//   两阶段(块内 (32,8),块间按行分段):
//     块数        16     32     64    128    256    512   1024   2048   4096
//     占峰值      22%    42%    71%    91%    94%    93%    91%    91%    91%
//     ← 参考解就在 256 那一档(下面的公式给出的 segs=16)
//
//   路 A(一个 block 包一整列,不做块间合并 —— 块数恒为 16,只能改块大小):
//     块形状   (32,4)      (32,8)      (32,16)      (32,32)
//     线程数    128         256          512         1024
//     占峰值    12%         23%          41%          72%
//
//   基线(一列一线程,2 个块):3.011 ms / 89 GB/s = 9%
//
//   散读映射(语义不变,只把 lane→数据的映射换成"同一个 warp 的 32 个 lane
//   读同一列的 32 个不同行"):
//     块数       128     256     512    1024    2048
//     占峰值     84%     70%     60%     36%     41%
//
// 五件必须写下来的事:
//
//   * **基线慢的原因不是访存。** 它每个元素只读一次(流量满分),相邻 lane 读
//     相邻的列(合并满分)。它只是**只有 512 个线程 = 2 个块** —— 128 个 SM
//     里 2 个在干活,所以只跑到 9%。
//
//   * **并行度是在飞的东西的乘积:块数 × 每块 warp 数 × 每 warp 在飞的访存数。**
//     路 A 那张表是这道题最值钱的一课:同一个算法、同样 16 个块,只把块从
//     128 线程加胖到 1024 线程,12% → 72%(6 倍),**一行代码都没改**。
//     也就是"调参"和"改算法"在这里的界限是模糊的 —— 因为瓶颈根本不是算法。
//
//   * **但块数这一维被 ceil(cols/32) 钉死了,这才是门槛能立住的原因。**
//     路 A 再怎么加胖也到不了 90%:块数上限 16,而块大小上限 1024 线程
//     (已经用满了),128 个 SM 里有 112 个是闲的。**想上 S 只有一条路:
//     把 rows 切开,让块数本身变多。** 反过来说:cols 只要大到几千,
//     路 A 自己就通了 —— 所以别把这条结论背成"两阶段一定比单阶段好",
//     它成立的前提是**块数不够**。
//
//   * **合并那一步的账要算,但它很便宜。** partial 的流量占比 = 2*segs/rows
//     —— **和 cols 无关**。segs=8 时 0.01%,segs=256 时 0.4%。真正会随段数
//     变贵的是第二个 kernel(它有 segs*cols 次加法,却只有 cols 个线程),
//     以及"每个块分到的活太少,摊销不掉自己的开销"。所以段数挑 8~256 之间
//     都在噪声里,不必抠。段数太少(1~4)才是真的亏 —— 那时候亏的是并行度。
//
//   * **块内那 8 个部分和只能用共享内存归约。** 同一列的 8 个 ty 分属 8 个
//     不同的 warp(shuffle 跨不了 warp)。漏一个 __syncthreads 就是"有时候对"。
// ---------------------------------------------------------------------------

#include "ctx.h"

// 每块的列数。32 = 一个 warp 宽 ⇒ 一个 warp 的一条 load 正好覆盖 32 个相邻
// float = 128 字节,也就是一整段 cache line。
#define TC 32
// 块内的行并行度。8 个线程分摊同一列:每个线程的依赖链短 8 倍,同时在飞的
// 访存多 8 倍 —— 这是用来"藏延迟"的,不是用来"少读"的(每个元素仍然只读一次)。
#define TR 8
// 第一阶段的目标块数(下界)。这张卡有 128 个 SM,每个 SM 放 1~8 个块才谈得上
// "填满"。实测 128 个块就到 91% 了,这里取 256 留一倍余量(实测最优档)。
#define TARGET_BLOCKS 256
// 每个线程至少要攒这么多行才值得开一段 —— 段数分得太细时,块会小到
// "分摊不掉自己的启动开销",而且第二个 kernel 的活会相对变重。
#define MIN_ROWS_PER_THREAD 64

__global__ void colsum_part(const float* __restrict__ x,
                            float* __restrict__ part,
                            int rows, int cols, int segs) {
    const int col = blockIdx.x * TC + threadIdx.x;
    const int seg = blockIdx.y;

    // 段的边界:让每段的行数尽量平均(rows 除不尽 segs 时前后差 1 行)。
    const int r0 = (int)((long long)rows * seg / segs);
    const int r1 = (int)((long long)rows * (seg + 1) / segs);

    float acc = 0.0f;
    if (col < cols) {                       // 列 tile 的尾巴:多出来的线程不读
        for (int i = r0 + threadIdx.y; i < r1; i += TR) {
            acc += x[(long long)i * cols + col];
        }
    }

    // 块内按列归约:同一列的 TR 个部分和分散在 TR 个 warp 里(每个 warp 的
    // ty 固定),所以只能用共享内存。
    //
    // 布局 [ty][tx]:同一行的 32 个 tx 落在 32 个不同的 bank 上,没有冲突。
    // 一旦改成 [tx][ty],同一个 warp 的 32 个 lane 会全部落在同一个 bank 上
    // —— 32 路冲突(03 题讲过同一件事)。
    __shared__ float sm[TR][TC + 1];
    sm[threadIdx.y][threadIdx.x] = acc;
    __syncthreads();
#pragma unroll
    for (int s = TR / 2; s > 0; s >>= 1) {
        if (threadIdx.y < s) {
            sm[threadIdx.y][threadIdx.x] += sm[threadIdx.y + s][threadIdx.x];
        }
        __syncthreads();   // 少一个就是"有时对有时错"
    }
    if (threadIdx.y == 0 && col < cols) {
        part[(long long)seg * cols + col] = sm[0][threadIdx.x];
    }
}

// 阶段二:把 segs 个部分和加起来。
// ⚠️ 它只有 cols 个工作项 —— 又回到"输出少"那一侧了,所以它必须**便宜**:
// 靠的是 segs 小(数据量 = segs*cols*4 字节),而不是靠它自己有多少并行度。
__global__ void colsum_merge(const float* __restrict__ part,
                             float* __restrict__ out,
                             int cols, int segs) {
    const int j = blockIdx.x * blockDim.x + threadIdx.x;
    if (j >= cols) return;
    float s = 0.0f;
    for (int c = 0; c < segs; ++c) {
        s += part[(long long)c * cols + j];
    }
    out[j] = s;
}

void colsum_launch(LaunchCtx& ctx) {
    // 段数:两个约束夹出来的 ——
    //   ① 第一阶段至少要有 TARGET_BLOCKS 个块(并行度);
    //   ② 每个线程至少要有 MIN_ROWS_PER_THREAD 行(摊销)。
    const int tiles = (ctx.cols + TC - 1) / TC;
    int segs = (TARGET_BLOCKS + tiles - 1) / tiles;              // ①
    const int seg_cap = ctx.rows / (TR * MIN_ROWS_PER_THREAD);   // ②
    if (segs > seg_cap) segs = seg_cap;
    if (segs < 1) segs = 1;
    if (segs > ctx.max_chunks) segs = ctx.max_chunks;

    dim3 block(TC, TR);
    dim3 grid(tiles, segs);
    colsum_part<<<grid, block>>>(ctx.x, ctx.partial, ctx.rows, ctx.cols, segs);

    const int mblock = 256;
    const int mgrid = (ctx.cols + mblock - 1) / mblock;
    colsum_merge<<<mgrid, mblock>>>(ctx.partial, ctx.out, ctx.cols, segs);
}

