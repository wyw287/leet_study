#     a2 = (a*a).sum(1, keepdim=True)
#     b2 = (b*b).sum(1, keepdim=True)
#     return torch.addmm(a2, a, b.t(), beta=1.0, alpha=-2.0).add_(b2.t())
#
# 语义完全一样,而且更好读 —— 实测 59.1x / 52.5x / 35.4x,大约是本实现的一半。
# 差别在于:addmm 写完了整个 (n,m) 输出之后,`.add_(b2.t())` 又要**再读写一遍**
# 输出(67MB)。而增广版把这步折进了矩阵乘,输出只写一遍。
#
# 所以这一节的重点不是"会用一个冷门技巧",而是那条可以反复用的判据:
# **先数输出被搬了几遍,再谈优化。**
#
# 【不要用】torch.cdist(...).pow_(2)
#
