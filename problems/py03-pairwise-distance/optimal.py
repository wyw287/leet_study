"""题目 py03 的参考解 —— 把 ‖a‖² 与 ‖b‖² 折进矩阵乘的维度

实测(d=32):
    square (n=m=4096)   基线 9.748 ms → 0.090 ms  → 108.2x
    odd    (质数维)     基线 4.979 ms → 0.065 ms  →  77.0x
    prime  (小规模)     基线 1.415 ms → 0.035 ms  →  40.5x

## 基线为什么这么慢

    diff = a.unsqueeze(1) - b.unsqueeze(0)    # (n, m, d) —— 广播成三维!
    return diff.pow(2).sum(dim=2)

它**物化了一个 (n, m, d) 的中间张量**。n=m=4096、d=32、f32 时那是 **2.1GB**,
而且这个量级的张量通不过 L2(72MB),pow 和 sum 两步还要各自再读写一遍 ——
实测基线要搬 6GB 以上,而最终输出只有 67MB。

> 加速比的量级可以这么估:输出被搬的遍数越少越快。
> 基线约搬了 4d = 128 个「输出大小」,本实现只搬 1 个,所以有 ~100x 的空间。

## 本实现:一遍出结果

把恒等式 ‖a-b‖² = ‖a‖² - 2a·b + ‖b‖² 里那三项**全部塞进一次矩阵乘**:

    â = [ a,  1,  ‖a‖² ]        (n, d+2)
    b̂ = [ -2b, ‖b‖², 1  ]       (m, d+2)

    â · b̂ = ‖a‖² - 2·(a·b) + ‖b‖²   ✓ 正是要的东西

关键在于那片 1 和 ‖·‖² **作为额外的维度参与矩阵乘** —— 它们只是 d+2 里多出来的
两列,算力代价可以忽略;而结果由矩阵乘内核一趟写出,没有任何 (n,m,d) 中间张量。

> 值得注意的是:‖a‖² 和 ‖b‖² 各只需要 n 个 / m 个数,却要参与每个 (i,j) 的计算。
> 把它们放进矩阵乘的维度里,正好让内核在处理每个输出元素时顺手就加上了 ——
> 这比"先算完矩阵乘、再加两个 bias"少了一趟完整的输出读写。
"""

import torch


def forward(ctx):
    a = ctx.x[:ctx.n]                  # (n, d)
    b = ctx.x[ctx.n:ctx.n + ctx.m]     # (m, d)
    n, m = ctx.n, ctx.m

    # 两个范数各只有 n 个 / m 个数,算起来几乎不花钱
    a2 = (a * a).sum(dim=1, keepdim=True)      # (n, 1)
    b2 = (b * b).sum(dim=1, keepdim=True)      # (m, 1)

    # 拼成增广矩阵。这两次 cat 只搬 (n,d+2) / (m,d+2),相对输出可忽略。
    ones_a = torch.ones((n, 1), dtype=a.dtype, device=a.device)
    ones_b = torch.ones((m, 1), dtype=b.dtype, device=b.device)
    A = torch.cat([a, ones_a, a2], dim=1)              # [a, 1, ‖a‖²]
    B = torch.cat([b * (-2.0), b2, ones_b], dim=1)     # [-2b, ‖b‖², 1]

    return A @ B.t()


# ---------------------------------------------------------------------------
# 【更容易想到的写法,供对照】addmm
