"""题目 py03 的性能基线:照定义写,用广播把 (n, m, d) 的差张量真的摊出来。

这份基线**不是**"故意写烂"的 —— 它就是绝大多数人第一次写这道题的样子,
每一步 API 都用得对,数值上也完全正确(它和参考解的对拍误差在 1e-6 量级)。
它慢的原因是**它真的把那个中间张量造了出来**。

以 square 用例(n = m = 4096, d = 32)为单位,沿 eager 的算子数一遍访存:

    a.unsqueeze(1) - b.unsqueeze(0)   (n,1,d)-(1,m,d) -> (n,m,d)   写 2.1GB         -> 2.1
    .pow(2)                                                       读 2.1 + 写 2.1   -> 4.2
    .sum(dim=2)                                                   读 2.1 + 写 0.067 -> 2.2
                                                                   -----------------------
                                                                   合计 ≈ 8.5GB

8.5GB / 1008 GB/s ≈ 8.4ms(实测 9.73ms,有效带宽约 870 GB/s = 峰值的 86%)。
而**真正需要的结果只有 67MB**(n×m×4B)—— 也就是说 99% 的显存流量搬的是一个
本可以不存在的 (n, m, d) 张量。

为什么会放大这么多?因为中间张量的元素数是**三个维度相乘**:n·m·d = 5.4 亿,
而输入加起来只有 rows·d = 26 万。d 每翻一倍,垃圾流量就翻一倍;
n 或 m 再翻一倍,垃圾流量翻四倍 —— 而真正要写的输出只翻一倍。

物理上的出路只有两条:
  ① 让中间张量不存在 —— 用一次矩阵乘把 d 这一维"吸收"掉(算力换带宽);
  ② 让它小到能留在 L2 里(分块)—— 但在 eager 里要付每块好几个内核的启动开销。

基线的作用是给出分母。它同时也是一个警告:这段代码在 n=m=50000 时会直接
OOM(中间张量 320GB),而它看起来是那么无辜。
"""
import torch


def forward(ctx):
    a = ctx.x[:ctx.n]                                # (n, d)
    b = ctx.x[ctx.n:ctx.n + ctx.m]                   # (m, d)

    diff = a.unsqueeze(1) - b.unsqueeze(0)           # (n, 1, d) - (1, m, d) -> (n, m, d)
    return diff.pow(2).sum(dim=2)                    # (n, m)
