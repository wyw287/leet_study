// 题目 06:矩阵乘法(分块 GEMM)
//
//   out[i][j] = Σ_k a[i][k] * b[k][j]        (三个矩阵都是 n×n,row-major)
//
// 只在本文件里写代码。device 内存的分配、数据搬运、计时、校验、越界检测
// 都由框架完成 —— 你只需要写 kernel 和决定启动配置。
//
//   ctx.a    const float*  device 指针,n×n
//   ctx.b    const float*  device 指针,n×n
//   ctx.out  float*        device 指针,n×n,需要你写入
//   ctx.n    int           矩阵边长
//
// 基线(一个线程算一个输出、每次 FMA 都从全局内存取数)是**完全正确**的,
// 你的任务不是「让它对」,而是**让它少读**。
//
// ---------------------------------------------------------------------------
// 先算清楚基线为什么慢 —— 这道题的全部内容都在这个算式里
// ---------------------------------------------------------------------------
// n=2048 时,一个输出元素要读 a 的一整行(n 个 float)和 b 的一整列(n 个),
// 也就是 2n = 4096 次读取 = 16KB;4.19M 个输出加起来是 68.7 GB 的访存请求。
//
// 但这题真正需要搬的字节只有 3 × 16MiB = 48MiB。平均每个字节被请求了 1365 次。
//
// 重复请求不等于重复搬 DRAM(48MiB 装得进 L2,大部分会命中缓存),但它们
// **每一条都要占一条访存指令、占一个 L1 wavefront**。L1↔寄存器这条路的吞吐
// 是每 SM 每 cycle 128B,而 4090 有 128 个 SM、2.5GHz。基线的实测耗时是 3.23ms,
// 而 DRAM 只需要 50µs、算力只需要 210µs —— 慢的十几倍全在「把数喂给 FMA」这条路上。
//
// 所以修法是提高**算术强度**:让每个搬进来的字节,参与尽可能多次 FMA。
//
// ---------------------------------------------------------------------------
// 1) 写 kernel
// ---------------------------------------------------------------------------
__global__ void matmul(const float* __restrict__ a,
                       const float* __restrict__ b,
                       float* __restrict__ out,
                       int n) {
    // TODO: 分三步做 —— 共享内存分块 → 寄存器分块 → 写回。下面每一段都有坑。
    //
    // ── 第一步:共享内存分块 ─────────────────────────────────────────────
    // 让一个线程块负责 out 的 TILE×TILE 一块(比如 32×32 或 64×64)。
    // 算这一块要用的数据是 a 的 TILE×n 条带和 b 的 n×TILE 条带;
    // 沿着 k 方向**一块一块地**搬:每一轮只搬 a 的 TILE×TILE 和 b 的 TILE×TILE
    // 进共享内存,算完这一轮的 k 再搬下一轮。
    //
    //   __shared__ float as[TILE][TILE];
    //   __shared__ float bs[TILE][TILE];
    //   for (int t = 0; t < (n + TILE - 1) / TILE; ++t) {
    //       // 256 个线程协作搬 2×TILE×TILE 个元素,越界的填 0
    //       __syncthreads();
    //       // 每个线程只从共享内存里取数做 FMA
    //       __syncthreads();     // ← 为什么这里必须有?
    //   }
    //
    // 一个字节从全局内存搬进来一次,就被 TILE 个输出复用 —— 请求量降到 1/TILE。
    //
    // ── 第二步:寄存器分块(这一步才是分水岭)────────────────────────────
    // 只做第一步会撞上另一堵墙:共享内存和 L1 在芯片上是同一块 SRAM,
    // LDS 和 LDG 走同一条流水线、吞吐都是每 SM 每 cycle 128B。
    // 一个线程只算一个输出的话,每个 FMA 要配 2 次共享内存读 → 上限就是
    // 「每 cycle 128B ÷ 8B = 16 次 FMA」,只有峰值的 1/8。
    // **实测:只做第一步是 1.17x —— 比你想象的少得多,几乎等于白做。**
    // (基线本来就有 L1 和广播帮着兜底,所以共享内存并没有更便宜。)
    //
    // 让一个线程算 R×R 个输出(常用 R=4):
    //
    //   float acc[R][R] = {0};
    //   for (int k = 0; k < TILE; ++k) {
    //       float ar[R], br[R];
    //       for (int i = 0; i < R; ++i) ar[i] = as[ty*R + i][k];
    //       for (int i = 0; i < R; ++i) br[i] = bs[k][tx*R + i];
    //       for (int i = 0; i < R; ++i)
    //           for (int j = 0; j < R; ++j)
    //               acc[i][j] += ar[i] * br[j];
    //   }
    //
    // 读 2R 个值 → 做 R² 次 FMA。R=4 时是「读 8 个值做 16 次 FMA」,
    // 每次访存摊到 2 次 FMA,是第一步的 4 倍。acc/ar/br 必须全部待在寄存器里,
    // 也就是说**所有下标都必须是编译期常数** —— 内层循环写成
    // `#pragma unroll` + 常数边界,别用运行时变量。
    //
    // ── 第三步:写回 ────────────────────────────────────────────────────
    // 每个线程把自己那 R×R 个结果写到 out。**要判边界**:n 不整除 TILE 时,
    // 最后一块 tile 会伸出矩阵外。n=1531 那个用例专门考这个。
    //
    // ── 三个必须同时成立的细节 ──────────────────────────────────────────
    // * **越界填 0,不要跳过。** 搬 tile 时越界的位置填 0.0f,这样 k 方向
    //   就能一路算到底、内层循环一个分支都不用判(0 乘任何数都是 0,不影响结果)。
    //   代价是 k 方向多算了几个无效的 0,收益是内层循环干干净净。
    // * **搬 tile 的全局读要合并。** 用 `for (i = tid; i < TILE*TILE; i += nthreads)`
    //   这种扁平索引,相邻线程读相邻的列;写成二维嵌套循环反而容易错开。
    // * **__syncthreads() 一次都不能漏,也不能放进分支。** 少了「算完再搬」
    //   那一处,快的线程会把慢的线程还在读的数据覆盖掉 —— 这种错**有时对有时错**,
    //   框架会把每个用例重复跑几次来抓它(verify.repeat),但你更该靠 racecheck。
    //
    // 卡住了先看 `leet solution 06`,那里有一份能跑到参考评级的实现。
}

