    //
    // 思路(一个 warp 算一行,不要一上来就写代码,先把这三步想清楚):
    //
    // ── 第一步:把「谁算哪一行」和「算这一行的哪个位置」拆开 ──────────────
    //   一个 warp 负责一行,行号由 warp 号决定;行内位置由 lane 决定:
    //
    //       const int lane = threadIdx.x & 31;          // 行内位置
    //       const int warp = (blockIdx.x * blockDim.x + threadIdx.x) >> 5;   // 行号
    //
    //   于是内层循环写成「lane 跨步」而不是「连续」:
    //
    //       for (int col = lane; col < n; col += 32) acc += rowp[col] * x[col];
    //
    //   现在同一条 load 指令里,32 个 lane 读的是 rowp[lane]、rowp[lane+1] ……
    //   **连续的 128 个字节 = 4 个 sector**,原来的 32 个 sector 变成 4 个。
    //
    // ── 第二步:一个 warp 内部把 32 个部分和加起来 ────────────────────────
    //   用 warp shuffle,不需要共享内存、不需要 __syncthreads(因为参与归约的
    //   32 个线程本来就在同一个 warp 里,硬件保证它们的执行是锁步的):
    //
    //       #pragma unroll
    //       for (int off = 16; off > 0; off >>= 1)
    //           acc += __shfl_down_sync(0xffffffffu, acc, off);
    //       if (lane == 0) y[row] = acc;
    //
    //   __shfl_down_sync(mask, v, k) 的语义:每个 lane 拿到「lane + k」那个 lane
    //   的 v。k 从 16 折半到 1,五步之后 lane 0 手里就是全 warp 的和。
    //
    // ── 第三步:让线程数不必等于 m ────────────────────────────────────────
    //   一个 warp 一行时,线程数被 m 绑死了(m=257 就只有 257 个线程在干活)。
    //   用 grid-stride 让固定大小的网格反复领行号:
    //
    //       for (int row = warp; row < m; row += total_warps) { ... }
    //
    //   注意 `row` 只跟 warp 号有关 —— 它是 warp 内**一致**的,不会让 warp 分叉。
