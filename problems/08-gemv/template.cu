// ---------------------------------------------------------------------------
// 三个会真出错的坑(和性能无关,是正确性)
// ---------------------------------------------------------------------------
// * **边界让循环条件自己兜住,不要手动加分支。** `for (col = lane; col < n; col += 32)`
//   本身就是边界安全的:col 从 lane 开始以 32 递增,一旦 >= n 就停,不可能越界。
//   n=129 时 lane 0 走 5 轮(col = 0,32,64,96,128)、lane 1..31 各走 4 轮 ——
//   **走的轮数不一样完全没关系**:少走的那几个 lane 的 acc 保持 0,
//   而 0 加进和里不影响结果(n < 32 时会有 lane 一轮都不走,同理)。
//   反过来,手动写 `if (lane < n) ... else ...` 这种"补一刀"的代码,极容易顺手把
//   shuffle 也圈进分支里(见下一条),或者把边界写成 `lane <= n` 而多读一个。
//   能靠循环条件表达的边界,就别用手写分支表达。
//
// * **__shfl_down_sync 的 mask 必须是 0xffffffff,而且调用时 32 个 lane 都得活着。**
//   它是**集合操作**:硬件要保证参与 shuffle 的 lane 在执行同一条指令。
//   把 shuffle 放进 `if (lane < n)` 这类会分叉的分支里,就是未定义行为
//   (可能挂住,也可能读到垃圾 —— 典型的「有时对有时错」)。
//   正确的结构是:循环(可能分叉)→ **重新汇合** → shuffle(全 32 个 lane 一起)。
//
// * **多写一个 0 不会错,少写一个才会。** 归约完之后是 lane 0 写 y[row],
//   别的 lane 一定不能也去写(那是在跟 lane 0 抢同一个地址,结果不确定)。
