// 题目 08:矩阵-向量乘(GEMV)
//
//   y[r] = Σ_c a[r][c] * x[c]          a 是 m×n(row-major),x 长 n,y 长 m
//
// 只在本文件里写代码。device 内存的分配、数据搬运、计时、校验、越界检测
// 都由框架完成 —— 你只需要写 kernel 和决定启动配置。
//
//   ctx.a  const float*  device 指针,m×n,row-major(a[r][c] 在 a[r*n + c])
//   ctx.x  const float*  device 指针,长度 n
//   ctx.y  float*        device 指针,长度 m,需要你写入
//   ctx.m  int           行数
//   ctx.n  int           列数
//
// 基线(一个线程算一行)是**完全正确**的,你的任务不是「让它对」,而是
// **让它把 128MiB 搬得更快**。

// ---------------------------------------------------------------------------
// 先想清楚这题的瓶颈在哪 —— 这道题的全部内容都在下面这两段里
// ---------------------------------------------------------------------------
// (一)算力绝对不是瓶颈。128MiB 的矩阵乘 32M 次 FMA,4090 的 FP32 是 82.6 TFLOPS,
//      算完只要 0.8µs;而把这 128MiB 从显存搬进来要 133µs(1008 GB/s)。
//      差两个数量级 —— 所以**任何「少算一点」的优化都是白费**,包括把
//      `acc += a*x` 换成 FMA、把循环展开、少用一个寄存器,全都不会让耗时动一下。
//      这题唯一有意义的动作是「让同样多的字节搬得更快」。
//
//      (对照 06-matrix-mul:那道题里 a 的每个字节会被复用 2000 次,所以正解是
//       共享内存分块 + 寄存器分块,想办法**提高**算术强度。这题相反 ——
//       每个字节只用一次,分块、共享内存、数据复用**一个都不需要**。
//       同一个作者写这两道题,会得出完全相反的结论。)
//
// (二)基线慢的不是「字节数」,是「请求数」。基线一个线程读一整行,线程内部是
//      连续的,但**同一个 warp 的 32 个线程读的是相隔 n 个 float 的 32 个不同行**:
//      一条 load 指令被拆成 32 个 32 字节的 sector(1024 字节),这次只有 128 字节
//      有用。剩下的字节并没浪费(同一线程的后 7 次迭代会用掉,一个 warp 的工作集
//      只有 1KB,L1 装得下),所以 DRAM 流量是准的 —— 多出来的是**请求**。
//      L1 每 cycle 只处理 4 个 sector,所以这种取法比连续取法慢 8 倍。
//
//      基线还有第二个毛病:它只有 m 个线程。m=4096 时 = 16 个块,128 个 SM 里
//      112 个在闲着。

