"""题目 py04 的性能基线:先排序,再取第一个。

这份基线**不是**「故意写烂」的 —— 它是一个非常自然的直觉:

    「我要的是位置,不是数值 —— 那就先把这一行排好序,位置自然就出来了。」

`argsort` 一步就把「顺序」和「位置」都给你了,写起来最短。它也是很多人在
不知道/想不起 `max(dim=1)`、`argmax` 时的第一反应。数值上它完全正确。

但代价是:为了产出那个**你根本不需要的完整顺序**,它必须把整行数据按位/按桶
搬好几趟,而且每一趟的写目标是散的(置换写回,scatter)—— 散写打不满带宽。

实测(8192×4096 f32,134MB,4090):

    x.argsort(dim=1, descending=True)        1.764 ms    有效带宽  76 GB/s
    x.sort(dim=1)                            1.764 ms
    x.sum(dim=1)          (对照:一遍顺序读)  0.145 ms    有效带宽 924 GB/s
    x.max(dim=1)          (同样是一遍顺序读)  0.147 ms
    4090 峰值带宽                                        1008 GB/s

**同一份数据、同一个答案,相差 12 倍 —— 差别只在访存模式。**
排序只跑到了峰值带宽的 7.5%,而归约几乎是贴着带宽墙在跑。

为什么会这样?因为排序不是「一次遍历」:

  * 一次 radix 排序要按 8 位一组把 32 位键过 4 遍,每遍都要读进来、算出目标位置、
    再写出去;
  * 而且 `argsort` 还得把**下标**跟着键一起搬家 —— 要搬的数据量直接翻倍
    (下标是 int64,比 f32 的键还大一倍);
  * 写回是置换:相邻线程写到的目标地址不相邻,cache line 只能写进去一部分
    就有用 —— 显存带宽被浪费掉一大半。

一句话:**排序的代价不在「比较」,在「把每个字节搬好几遍,还搬得不利索」。**

基线的作用是给出分母,也是一个警告:s = 8、cols = 32768 时它就是十几毫秒,
而真正要的只是每行一个数字。
"""
import torch


def forward(ctx):
    # 降序排好序,第 0 列就是最大值的原位置 —— 一行代码,直觉满分
    order = ctx.x.argsort(dim=1, descending=True)     # (rows, cols) int64
    return order[:, 0].to(torch.int32)                # out 缓冲是 int32
