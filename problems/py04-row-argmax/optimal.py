"""题目 py04 的参考解 —— 用 argmax,别用 argsort

实测(同一份数据、同一个答案,只有访存模式不同):

    用例                      基线 argsort      本实现 argmax     加速比
    square (8192×4096)        1.723 ms          0.149 ms          11.53x
    tall   (2048×16384)       6.447 ms          0.149 ms          43.42x
    odd    (6151×2053)        0.813 ms          0.065 ms          12.60x

看 `tall` 那一行:**同一个解答在两种形状下拿到 11.53x 和 43.42x** ——
差距全来自基线在 `tall` 上崩得更惨,而不是解答变好了。这正是本题要教的:

    归约的代价只取决于「读多少字节」,与形状无关;
    置换的代价还取决于「搬得顺不顺」。

基线 `argsort` 要知道全部元素的顺序,而那是一份排好序的**完整副本**;
我们只想要一个下标。多出来的 99.99% 的工作全是白干的。
"""

import torch


def forward(ctx):
    # argmax 是一趟流式扫描:每个线程走过自己负责的元素,只记住「目前最大的那个
    # 在哪」。不需要比较所有元素两两之间的大小关系,自然也不需要排序。
    #
    # 代价只取决于读多少字节 —— 所以 square 和 tall 的耗时几乎一样
    # (0.149 ms vs 0.149 ms),尽管两者的行列数差了 4 倍。
    #
    # out 缓冲是 int32,而 argmax 返回 int64,所以要转换(这一步很便宜)。
    return torch.argmax(ctx.x, dim=1).to(torch.int32)


