// 值得亲手验证的三件事:
//
// 1. **把"轨道"切小一点会怎样?** 比如只让最外层成对:一个线程管
//    (b,i,j) 和 (mb,i,j),行内和层内的镜像还是各读各的。8 次读的 4 个时刻
//    塌缩成 2 个 —— **实测 68%(B)**,拿不到 S。物理原因:剩下的那个时刻是
//    (b,i) ↔ (b,mi),距离最大 33.5M 个元素,照样超出 L2 的窗口。
//    注意这里有个反直觉的点:那个写法的"逻辑读次数"从 8 降到了 4,
//    但**显存流量几乎没变** —— 因为落在同一时刻上的重复读,本来就被
//    L1/L2 合并掉了,一分钱不花。**"读几次"和"落在几个时刻上"是两本账。**
//
// 2. **换成 4096² 的二维图做同样的 4 向平均,还有优化空间吗?**
//    没有 —— 64MiB 装得进 72MB 的 L2,几个时刻全被缓存接住,基线和
//    参考解只差几个百分点。**同一份代码,瓶颈随数据规模而变**:这题
//    考的是"复用距离 vs 缓存容量"这个比值,不是某个固定的写法。
//    (想亲手验一把,把用例改小跑一遍就行 —— 题面的用例都是 268MB 量级,
//     故意不留"装得进 L2"的样本,否则评级会虚高到 100% 以上。)
//
// 3. **张量的形状也参与决定这道题有没有优化空间。** 同样是 268MB,
//    摊成 2048×256×128 时切片只有 128KB,(b,i) ↔ (b,mi) 那一组就落回
//    "免费"那一档,基线能跑到 68% —— 梯度全没了。**"张量比 L2 大"是
//    必要条件,不是充分条件。** 可以自己改形状实测验证这个趋势。
