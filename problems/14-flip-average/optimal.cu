// 题目 14 的参考解
//
// 核心动作只有一个:**把"一个线程算一个输出"换成"一个线程管一个轨道"。**
//
// 关键观察:位置 p = (b,i,j) 的 8 个 tap 是
//
//     {(b|mb, i|mi, j|mj)}          mi = h-1-i,mb = d-1-b
//
// 而它的镜像位置 (b,i,mj) 的 8 个 tap,是**同一组**(只是顺序不同):
// 因为"取镜像"这个动作在每个轴上是独立的,对三个轴各取一次镜像,
// 得到的就是同一个集合。8 个位置,每一个的 tap 集合都等于这一组。
//
// 于是有两个结论,一个关于算、一个关于读:
//
//   ① 这 8 个位置的值**全都相等**(同一个集合、同一个平均值)。
//      out 是 8 重对称的 —— 一个轨道只需要算一次。
//   ② 既然 8 个线程算的是同一个值、读的是同一组数据,那就让**一个线程**
//      把这 8 个读进来(每个只读一次),算一次,写 8 个。
//
// 读的次数从 8 降到 1,写的次数一次没多。而这道题的瓶颈就在读:
//
//   基线:每元素读 8 次。这 8 次不是同时发生的,而是落在 4 个时刻上
//         (行内那一对 j/mj 天然同时,不用管);另外 3 个时刻的复用距离
//         最大到 h*w = 33.5M 个元素 ≈ 400MB 以上的流量,远超 72MB 的 L2
//         ⇒ 真的再走一趟显存。等效流量 ≈ 3.5 读 + 1 写。**实测 41%。**
//   本解:8 次读塌缩成 1 个时刻,每元素读 1 次、写 1 次。
//         等效流量 = 1 读 + 1 写。**实测 98%(984 GB/s)。**
//
// 访存模式一点没变:8 个读、8 个写,每一个都是 warp 内 32 个 lane 连续的
// 128 字节(4 个 sector 全用上)。**变的只是"谁在什么时候读"。**
//
// ---------------------------------------------------------------------------
// 基本域:为什么取 (d+1)/2 × (h+1)/2 × (w+1)/2(向上取整是关键)
// ---------------------------------------------------------------------------
// 让每个轨道只被一个线程领走:取每个轴上"靠前的那一半"作为代表元。
// min(x, n-1-x) 的值域是 [0, (n-1)/2],大小 = (n+1)/2(整数除法,奇数时
// 把正中间那个也含进来)。
//
//   偶数 n:代表元 0..n/2-1,{x, n-1-x} 两两配对,覆盖 [0,n) 一次
//   奇数 n:代表元 0..(n-1)/2,**中间那个 n/2 自己是自己的镜像**,
//          它被这个线程写两次 —— 地址相同、值相同,而且**是同一个线程**,
//          所以既不是竞态也不会写错。漏掉它才是 bug(会被毒值抓到)。
//
// 写 8 个位置时不要特判:让 mj == j、mi == i、mb == b 的情形自然发生,
// 重复的写自己就退化成"写两次同一个地址"。**特判反而是 bug 的来源** ——
// 少写一次和漏写一个位置,前者看不出来,后者要等到对拍才暴露。

#include "ctx.h"

__global__ void flip_avg(const float* __restrict__ x,
                         float* __restrict__ out,
                         int d, int h, int w) {
    const int j = blockIdx.x * blockDim.x + threadIdx.x;   // 最内层仍然沿它走
    const int i = blockIdx.y;
    const int b = blockIdx.z;

    // 基本域:只保留 1/8 的位置,每个位置代表一个轨道
    if (j >= (w + 1) / 2 || i >= (h + 1) / 2 || b >= (d + 1) / 2) return;

    const int mb = d - 1 - b;
    const int mi = h - 1 - i;
    const int mj = w - 1 - j;

    const int s0 = b * h * w;    // 第 b  层
    const int s1 = mb * h * w;   // 第 mb 层
    const int r0 = i * w;        // 第 i  行
    const int r1 = mi * w;       // 第 mi 行

    // 读 8 个(每个元素在整个 kernel 里只会被读这一次),算一次
    const float v = 0.125f * (x[s0 + r0 + j] + x[s0 + r0 + mj]
                            + x[s0 + r1 + j] + x[s0 + r1 + mj]
                            + x[s1 + r0 + j] + x[s1 + r0 + mj]
                            + x[s1 + r1 + j] + x[s1 + r1 + mj]);

    // 写 8 个:8 重对称 ⇒ 值都一样
    out[s0 + r0 + j]  = v;
    out[s0 + r0 + mj] = v;
    out[s0 + r1 + j]  = v;
    out[s0 + r1 + mj] = v;
    out[s1 + r0 + j]  = v;
    out[s1 + r0 + mj] = v;
    out[s1 + r1 + j]  = v;
    out[s1 + r1 + mj] = v;
}

void flip_avg_launch(LaunchCtx& ctx) {
    // 线程数不再等于输出个数,而是 1/8 那一量级:基本域 = 向上取整的三个半轴。
    // 每个线程负责的行内位置数 = (w+1)/2,block.x 取 64 正好一个 warp 两行。
    const dim3 block(64, 1, 1);
    const dim3 grid(((ctx.w + 1) / 2 + block.x - 1) / block.x,
                    (ctx.h + 1) / 2,
                    (ctx.d + 1) / 2);
    flip_avg<<<grid, block>>>(ctx.x, ctx.out, ctx.d, ctx.h, ctx.w);
}

