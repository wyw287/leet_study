// 题目 14:八向翻转平均
//
// 只在本文件里写代码。
// device 内存的分配、数据搬运、计时、校验、越界检测都由框架完成 ——
// 你只需要写 kernel 和决定启动配置。
//
// 语义:x 是 d×h×w 的三维张量(row-major,线性下标 ((b*h + i)*w + j))。
// 对每个位置,把它在「三个轴各自翻不翻转」这 8 种组合下的对应位置求平均:
//
//     out[b][i][j] = (1/8) * Σ x[b 或 d-1-b][i 或 h-1-i][j 或 w-1-j]
//
// 换个说法:out 是 x 在"翻转群"下的对称化。它一定满足 8 重对称:
// 把一个位置和它的 7 个镜像位置写进 out,值全都一样。
//
//   ctx.x    const float*  device 指针,长度 ctx.d*ctx.h*ctx.w
//   ctx.out  float*        device 指针,同形状,需要你写入
//   ctx.d    int           最外层(层)
//   ctx.h    int           中间层(行)
//   ctx.w    int           最内层(列,显存里连续的那一维)
//
// 三个维度都可能是奇数,而且不保证是 2 的幂(用例里有 1021×509×131 这种,
// w=131 一个 warp 的尾巴就是空的)。
// 所有位置都要写:框架在校验前会把 out 填成毒值,漏写一个就会被抓到。

