    // 它是对的、合并访问是满分的、sector 一个字节都没浪费 ——
    // 但它是这道题的**基线**,因为它在另一个维度上亏了:
    //
    //   先把账算清楚(这决定了整道题的方向):
    //     输出:每元素写 1 次 —— 没有可省的
    //     输入:每元素被读 8 次,而这 8 次**不是同时发生的**,
    //           而是分散在四个时刻上
    //
    //   8 个 tap 分成四组,落在四行上:
    //       (b,i)  (b,mi)  (mb,i)  (mb,mi)      mi = h-1-i,mb = d-1-b
    //   组内那两个位置(第 j 个和镜像 mj)在同一行内,最多隔 w = 4096 个元素
    //   = 16KB,**总是同时命中,不用管它**。要算的是组与组之间:
    //
    //       (b,i) ↔ (b, mi):最多  h*w = 33.5M 个元素
    //       (b,i) ↔ (mb, i):恒等于 h*w = 33.5M 个元素
    //
    //   判据不是"访问模式好不好看",而是**复用距离**:同一个元素两次被用到
    //   之间,隔了多少字节的流量。kernel 每处理一个输出平均搬十来个字节,
    //   所以"隔了 33.5M 个元素"≈"隔了 400MB 以上的流量"。
    //
    //   **L2 只有 72MB。** 隔了几十万个元素的重读,缓存接不住,
    //   只能再走一趟显存 —— 实测四个时刻里有三个真的落空。
    //
    // TODO: 想办法让"落空的那几次读"消失。
    //
    //   提示 —— 盯着一个位置看:它的 8 个 tap 是
    //       {(b|mb, i|mi, j|mj)}
    //   现在看它的镜像位置 (b, i, mj) 的 8 个 tap,是不是**同一组**
    //   (只是顺序不同)?再看 (mb, i, j)、(mb, mi, mj)…… 8 个位置,
    //   每一个的 tap 集合都是这同一组。
    //
    //   于是:既然要读的是同一组数据、算出来的又是同一个值,
    //   **为什么要让 8 个线程各读 8 个?** 一个线程把这 8 个读进来
    //   (每个只读一次),算出那一个平均值,然后写 8 个位置 —— 8 次读
    //   塌缩成 1 个时刻,写的次数一次没多。
    //
    //   这样线程总数变成原来的 1/8:让每个线程只负责"基本域"里的一个位置,
    //   它的 8 个镜像由它自己一起写掉。基本域怎么取?每个轴上取前一半:
    //   b < (d+1)/2,i < (h+1)/2,j < (w+1)/2 —— 数一数,
    //   {b, d-1-b} 是不是正好把 [0,d) 覆盖一遍?
    //
    //   自己动手验证下面两件事(这道题最容易错的地方就在这):
    //     ① d/h/w 是奇数时,中间那一层/行/列**是自己的镜像**。
    //        这时上面那个基本域还覆盖得全吗?会不会漏掉中间的层?
    //     ② 会写重吗?同一个线程把同一个地址写两次、两次的值一样,
    //        这算不算竞态?(提示:同一个线程内部没有竞态;但如果你把
    //        基本域取成别的样子,让**两个不同的线程**去写同一个地址,
    //        racecheck 就会报你。)
    //
    //   实测的梯子(两个用例成绩一致):
    //       基线(8 次读,4 个时刻)                    41%   ——
    //       只把最外层成对(塌缩成 2 个时刻)            68%   B
    //       一个线程管一个轨道(读 8 写 8,只读一遍)    98%   S
