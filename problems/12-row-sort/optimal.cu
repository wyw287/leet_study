// 题目 12 的参考解(计数排序 + 块内私有化 + 共享内存暂存写回)
//
// ===========================================================================
// 这道题的全部秘密是:**一次比较都不做**。
// ===========================================================================
//
// 值域只有 0..99,所以「排好序」和「数一遍再按顺序铺开」是同一件事:
//
//     ① 把整行搬进共享内存(全局内存只读这一遍),同时清零直方图
//     ② 数直方图:atomicAdd(&hist[v], 1)
//     ③ 排他前缀和 → 每个值的起始下标(游标)
//     ④ 散射:o[atomicAdd(&cur[v], 1)] = v   —— 注意是散射到**共享内存**
//     ⑤ 合并写回:y[i] = o[i]                 —— 这一步访存是合并的
//
// 一共 4 次 __syncthreads。对比三种实现的「趟数」:
//
//     奇数-偶数换位排序(基线)      cols = 1024 次屏障
//     bitonic 排序                 log²(cols)/2 = 55 次屏障
//     本参考解                     4 次屏障
//
// 而三者的 DRAM 流量**完全一样**(读 4 字节 + 写 4 字节 = 8 字节/元素)。
// 也就是说这道题的成本几乎就是「屏障次数 × 屏障的价钱 + 配套的指令发射」。
//
// 实测(4090,框架自动清 L2,big 用例 32768×1024 = 134MB 读 + 134MB 写):
//
//     基线(1024 趟)                15.64 ms    1.00x   ← 根本没碰过带宽
//     bitonic(55 趟)                2.158 ms    7.24x   ← 仍然是指令/屏障受限
//     计数排序,散射直接写全局        0.454 ms   34.4x    ← 撞上另一堵墙(见下)
//     本参考解                       0.242 ms   64.6x    ← 268MB/0.242ms = 1107 GB/s
//
// 关于最后 1.9 倍 —— **这道题真正的第二个考点**:
//
//   散射的写地址是数据决定的。一个 warp 的 32 个线程会写到这一行 4KB 里的
//   32 个随机位置,于是**一条 store 指令被拆成几十个 L1 事务**
//   (合并访存时只要 1 个)。代价约等于「每写一个元素花掉一个 L1 wavefront」,
//   33.5M 次摊到 128 个 SM 上接近 190µs —— 和 266µs 的 DRAM 时间叠在一起,
//   就把 34x 卡在了那里。
//
//   解法不是"把散射变合并"—— 散射的写地址由数据决定,这件事改不掉。
//   能做的是**把散射挪到一个便宜的地方**:先散进共享内存,再从共享内存
//   顺序搬出去。于是
//     第 ④ 步:散射,但打在共享内存上(代价是 bank 冲突,几条 replay)
//     第 ⑤ 步:顺序写全局,一条 store 指令一个 L1 事务
//   共享内存那一步确实更贵了(冲突换了个地方,并没有消失),
//   但它买下的是:全局写从「每条 store 指令约 28 个 L1 事务」
//   变成「每条 store 指令 1 个事务」。用 4KB 片上内存换这个,划算。
//
// 说明:这个结构假设**一整行装得下共享内存**。2*cols 个 int 在 cols=1024 时
// 是 8KB,每 SM 驻留 8 个 block 正好 70KB(在 100KB 以内)。行再大一个数量级
// 就要换结构(分块 + 跨块前缀和,那就变成 11 题那样的多 kernel 问题了)。
//
// 实测(4090,框架自动清 L2):
//     big     32768×1024   0.242 ms   64.64x   1107 GB/s
//     ragged  32749×1021   0.247 ms   66.13x   1085 GB/s

#include "ctx.h"

#define NBINS 100

__global__ void row_sort(const int* __restrict__ x,
                         int* __restrict__ y,
                         int rows, int cols) {
    extern __shared__ int sh[];         // 2*cols 个 int
    int* s = sh;                        // sh[0..cols)     输入行
    int* o = sh + cols;                 // sh[cols..2cols) 输出行
    __shared__ int hist[NBINS];         // 直方图(每块私有)
    __shared__ int cur[NBINS];          // 散射游标(每块私有)

    const int r = blockIdx.x;           // 一个 block 一行
    if (r >= rows) return;              // 整块一起返回,不会在屏障处分叉
    const int t = threadIdx.x;

    const int* __restrict__ xr = x + (long)r * cols;
    int* __restrict__ yr = y + (long)r * cols;

    // ---- ① 清零直方图 + 搬行(全局内存只读这一遍)----------------------
    for (int b = t; b < NBINS; b += blockDim.x) hist[b] = 0;
    for (int i = t; i < cols; i += blockDim.x) s[i] = xr[i];
    __syncthreads();

    // ---- ② 直方图 ------------------------------------------------------
    // 原子加打在本块私有的共享内存上,不是全局内存上:33.5M 次原子加如果
    // 全挤在 100 个全局地址上,L2 会**按地址串行化**,这题立刻慢一个数量级
    // (07 题实测过:22 GB/s,峰值的 2%)。
    for (int i = t; i < cols; i += blockDim.x) atomicAdd(&hist[s[i]], 1);
    __syncthreads();

    // ---- ③ 排他前缀和 → 游标 -------------------------------------------
    // 另存一份 cur,不要把前缀和原地写回 hist:第 v 个线程要读 hist[0..v-1],
    // 别人写进去的前缀和会把还没读到的**计数**覆盖掉。
    //
    // 100 个桶、串行内层循环:这点延迟被下面那次 __syncthreads 一起等掉了,
    // 实测不值得再上并行扫描 —— 这道题的钱不在这儿。
    if (t < NBINS) {
        int sum = 0;
        for (int b = 0; b < t; ++b) sum += hist[b];
        cur[t] = sum;
    }
    __syncthreads();

    // ---- ④ 散射到共享内存 ----------------------------------------------
    for (int i = t; i < cols; i += blockDim.x) {
        const int v = s[i];
        o[atomicAdd(&cur[v], 1)] = v;
    }
    __syncthreads();

    // ---- ⑤ 合并写回 ----------------------------------------------------
    // 第 ④ 步已经把所有元素摆到最终顺序上了;这一步是纯搬运,
    // 地址连续 → 一条 store 指令一个 L1 事务。
    for (int i = t; i < cols; i += blockDim.x) yr[i] = o[i];
}

void row_sort_launch(LaunchCtx& ctx) {
    // block 取 256 而不是 1024。一行只有 1024 个元素,用 1024 个线程的话
    // 每个线程全程只干一件事;而每个 SM 最多驻留 2048 个线程 ——
    // 于是只有 2 个 block 在飞,掩盖访存延迟的能力差得多。
    //
    // 实测(同一个 kernel,只改这一个数,big 用例):
    //     block = 256    0.242 ms   64.6x
    //     block = 1024   0.353 ms   44.2x     ← 慢 1.46 倍
    // 这 1.46 倍不是"线程多干了活",而是"在飞的 block 少了"。
    // (bitonic 那一档 2.158 ms 也吃到了同一件事:它不得不用 1024 个线程,
    //  因为整行要在 1024 个线程之间交换。)
    const int block = 256;
    const size_t shbytes = (size_t)ctx.cols * 2 * sizeof(int);
    // 一个 block 一行:网格大小 = 行数
    row_sort<<<ctx.rows, block, shbytes, ctx.stream>>>(ctx.x, ctx.y,
                                                       ctx.rows, ctx.cols);
}
