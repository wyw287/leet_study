// 题目 12:行内排序(值域只有 0..99)
//
// 只在本文件里写代码。
// device 内存的分配、数据搬运、计时、校验、越界检测都由框架完成 ——
// 你只需要写 kernel 和决定启动配置。
//
// 语义:把 rows×cols 的行优先矩阵**逐行**升序排序,写进 y。
// 行与行之间完全独立。x 里的每个值都在 0..99 之间(这是题目契约,不是巧合)。
//
//   ctx.x     const int*  device 指针,长度 rows*cols(行优先)
//   ctx.y     int*        device 指针,长度 rows*cols,需要你写入
//   ctx.rows / ctx.cols   矩阵尺寸(运行时才知道)
//
// 输出必须**逐元素精确相等** —— 整数没有容差。而且所有位置都要写:
// 框架在校验前会把 y 填成毒值 0x5EED5EED,漏写一个元素就会被抓到。

#include "ctx.h"

// ---------------------------------------------------------------------------
// 1) 写 kernel
// ---------------------------------------------------------------------------
__global__ void row_sort(const int* __restrict__ x,
                         int* __restrict__ y,
                         int rows, int cols) {
    // 一个 block 负责一行(blockIdx.x 就是行号),分四步做:
    //
    //   ① 把这一行搬进共享内存;同时把直方图清零。
    //   ② 扫一遍共享内存里的行,给每个值记一笔:atomicAdd(&hist[v], 1)。
    //   ③ 对直方图做**排他前缀和**,得到每个值的起始下标(游标)。
    //   ④ 再扫一遍共享内存:y[atomicAdd(&cur[v], 1)] = v —— 每个元素
    //      落到"它那个值的下一个空位"上。
    //
    // 为什么这能打败一切比较排序?因为**它一次比较都不做**。
    // 比较排序的每一趟(冒泡的一趟、bitonic 的一个阶段)后面都必须跟一次
    // __syncthreads,而屏障是整块线程一起等的;趟数就是这道题的时钟。
    // 值域只有 100 种可能的时候,"排好序"= "数一遍再按顺序铺开",几步就完了。
    //
    // 每一步之间都要 __syncthreads(),而且不能放进分支里:
    //   * ①→② 之间:别人还没写完共享内存里的行,你就开始数了。
    //   * ②→③ 之间:直方图还在被别的线程加。
    //   * ③→④ 之间:**游标还没算完就开始散射,位置会撞车**。
    // 漏掉任何一个,结果都是"有时对有时错"——所以框架每个用例跑 3 遍。
    //
    // 提示(共享内存):整行是运行时才知道的 cols 个 int,要用动态共享内存;
    // 直方图和游标是固定的 100 个 int,可以直接用静态共享内存,两者可以共存:
    //
    //     extern __shared__ int s[];       // cols 个 int:整行缓存
    //     __shared__ int hist[100];        // 直方图
    //     __shared__ int cur[100];         // 散射游标
    //
    // 启动时把整行的字节数当第三个参数传进去:
    //
    //     row_sort<<<grid, block, (size_t)cols * sizeof(int)>>>(...);
    //
    // 踩坑提示:
    //   * 共享内存里的 hist 和 cur 都是**每块一份**的,别的块看不见,
    //     所以不需要原子操作以外的东西 —— 但也**绝不能**跨块共享。
    //     如果图省事把直方图放到全局内存里用 atomicAdd 累加,
    //     32M 次原子加会全部挤在 100 个地址上(L2 对同一地址是串行的),
    //     这题会立刻退化成一坨 —— 07 题讲过这件事。
    //   * 前缀和不要在原地做:第 v 个线程要读 hist[0..v-1],而别人写进去的
    //     前缀和会把还没读到的**计数**覆盖掉。用 cur 另存一份 —— 这不是
    //     性能问题,是正确性问题。
    //   * cols 是运行时值,而且不是 2 的幂(1021)、还可能比 blockDim 小(129)。
    //     跨步循环 `for (i = t; i < cols; i += blockDim)` 天然能处理,
    //     但**共享内存里没有被写到的位置是垃圾值,不要读它们**。
    //   * 第 ④ 步的写地址是**数据决定的**(scatter),这是本题唯一无法合并的
    //     访存。容易犯的一个错是这么想:"每个位置只写一次,总字节数没变,
    //     所以它不会是瓶颈" —— **这句话是错的**。一个 warp 的 32 个线程会写到
    //     这一行 4KB 里的 32 个随机位置,一条 store 指令因此被拆成几十个
    //     L1 事务(合并访存时只要 1 个)。你会发现代码写到这一步就停在
    //     34 倍左右上不去了,而离带宽墙还有 1.9 倍的距离。
    //     那 1.9 倍怎么拿?回头看题面「解法思路」的第 5 步。
}

