// 参考解 —— 一份能达到 S 级的实现。卡住了再看。
//
// 本题有两幕,大部分人只走完第一幕就停了。
//
// ---------------------------------------------------------------------------
// 第一幕:打断依赖链(1.00x → 2.9x)—— 纯 C++,不需要任何 intrinsics
// ---------------------------------------------------------------------------
// 原写法只有 1 个累加器,第 i 次加法必须等第 i-1 次算完。vaddsd 延迟 3 个周期、
// 吞吐 2 条/周期 —— 延迟摆在那里,吞吐就永远用不上,每 3 个周期才出 1 个元素。
//
// 拆成 4 路独立累加器就够了(实测 2.97x)。实测的阶梯:
//     1 路  1.00x      2 路  1.97x      4 路  2.97x
//     8 路  2.88x     16 路  2.88x
//
// 注意 4 路之后**再加累加器完全没有用**(8 路、16 路都还是 2.88x)。
// 这不是"收益递减",是换了一个瓶颈 —— 见第二幕。
//
// ---------------------------------------------------------------------------
// 第二幕:标量转换指令成了新的墙(2.9x → 5.9x)—— 这一步要写 SIMD
// ---------------------------------------------------------------------------
// 数据是 f32,累加必须用 double(精度,见题面"陷阱")。所以每个元素都要做一次
// float → double 的**拓宽转换**。写成 `a0 += (double)x[i]` 时,编译器为每个元素
// 生成一条 vcvtss2sd —— 一次只转 1 个 float。
//
// 而它在 Zen 3 上的吞吐只有 1 条/周期左右:4M 个元素 = 4M 条转换指令
// ≈ 1.2ms。于是 8 路、16 路累加器全都卡在同一个地方:加法早就不是瓶颈了,
// **转换是**。
//
// 解法是让转换也向量化:AVX2 的 vcvtps2pd 一条指令把 **4 个** float 转成
// 4 个 double。指令数直接降到 1/4,墙就没了,重新回到 DRAM 带宽上
// (实测 16MB / 0.70ms ≈ 24 GB/s,已经是这台机器单核的顺序读带宽)。
//
// 关键点:**编译器不会替你做这一步**。它既不能重排浮点归约(没有 -ffast-math),
// 也就不会把整个 "load → 拓宽 → 累加" 的模式向量化 —— 这个模式里含一个
// 浮点归约。所以第二幕只能手写。这也是本题唯一需要 intrinsics 的地方,
// 而且只用到最基础的 4 个:loadu / cvtps_pd / add_pd / storeu。
//
// ---------------------------------------------------------------------------
// 试过的死路(都实测过)
// ---------------------------------------------------------------------------
//   * 2 路累加器                       → 1.97x,链没填满
//   * 8 路、16 路标量累加器             → 2.88x,和 4 路一样,撞在 vcvtss2sd 上
//   * 串行 float 累加                   → 1.00x(延迟一样),而且 big 用例**判错**
//   * 先把 x 整块转成 double 再求和      → 更慢。多出 16MB 写 + 32MB 读,
//                                        访存翻三倍,而瓶颈本来就在访存
//   * 用 4 条 __m256d 链但每 8 个元素
//     只转低 4 个(漏掉高 4 个)          → 快,但答案是错的(会漏掉一半数据)
//
// 数值上完全安全:4 条向量链各自累加 n/32 项,最后 16 个 double 相加。
// 部分和量级只有原来的 ~1/32,累积舍入误差反而比串行更小 —— 实测与
// 参考解的偏差是 0(bit-identical 到 f64 输出的精度)。
// 这不是"用精度换速度",精度是变好的。

#include "ctx.h"
#include <immintrin.h>

void sum_reduce(Ctx& ctx) {
    const int64_t n = (int64_t)ctx.n;
    const float* __restrict x = ctx.x;

    // 4 条独立的 double 向量链,每条 4 个 lane —— 等价于 16 路累加器
    __m256d c0 = _mm256_setzero_pd();
    __m256d c1 = _mm256_setzero_pd();
    __m256d c2 = _mm256_setzero_pd();
    __m256d c3 = _mm256_setzero_pd();

    int64_t i = 0;
    for (; i + 32 <= n; i += 32) {
        const __m256 f0 = _mm256_loadu_ps(x + i +  0);
        const __m256 f1 = _mm256_loadu_ps(x + i +  8);
        const __m256 f2 = _mm256_loadu_ps(x + i + 16);
        const __m256 f3 = _mm256_loadu_ps(x + i + 24);

        // 一次 loadu 拿到 8 个 float,拆成低 4 个 + 高 4 个,
        // 各用一条 vcvtps2pd 拓宽成 4 个 double。
        c0 = _mm256_add_pd(c0, _mm256_cvtps_pd(_mm256_castps256_ps128(f0)));
        c0 = _mm256_add_pd(c0, _mm256_cvtps_pd(_mm256_extractf128_ps(f0, 1)));
        c1 = _mm256_add_pd(c1, _mm256_cvtps_pd(_mm256_castps256_ps128(f1)));
        c1 = _mm256_add_pd(c1, _mm256_cvtps_pd(_mm256_extractf128_ps(f1, 1)));
        c2 = _mm256_add_pd(c2, _mm256_cvtps_pd(_mm256_castps256_ps128(f2)));
        c2 = _mm256_add_pd(c2, _mm256_cvtps_pd(_mm256_extractf128_ps(f2, 1)));
        c3 = _mm256_add_pd(c3, _mm256_cvtps_pd(_mm256_castps256_ps128(f3)));
        c3 = _mm256_add_pd(c3, _mm256_cvtps_pd(_mm256_extractf128_ps(f3, 1)));
    }

    // 合并:16 个 double,树形相加
    double t[16];
    _mm256_storeu_pd(t +  0, c0);
    _mm256_storeu_pd(t +  4, c1);
    _mm256_storeu_pd(t +  8, c2);
    _mm256_storeu_pd(t + 12, c3);
    double s = 0.0;
    for (int k = 0; k < 16; ++k) s += t[k];

    // 收尾:32 路展开的余数(odd 用例 n=1000003,余数是 3)。
    // 漏掉这里是最容易犯的错 —— 8 路展开时漏掉 3 个元素,大半用例照样能过,
    // 只有 odd 会露馅。
    for (; i < n; ++i) {
        s += (double)x[i];
    }

    ctx.out[0] = s;
}
