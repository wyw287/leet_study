// 性能基线 —— 也是学习者拿到的起点代码。
//
// 这是**最自然的写法**:照着 sum = x[0] + x[1] + ... + x[n-1] 的定义直译。
// 它完全正确,数值上也挑不出毛病(用 double 累加)—— 问题只出在
// **这个循环里没有任何两个加法是互相独立的**。
//
// 每一次 s += x[i] 都要等上一次的 s 算完才能开始。现代 CPU 的浮点加法
// 延迟是 3~4 个周期,而吞吐是每周期 2 条 —— 于是这条链每 3~4 个周期
// 才吐出一个结果,CPU 的浮点加法单元有 90% 的时间在空转。
//
// 关键点:这不是"代码写得烂",而是**没人告诉编译器可以重排**。
// 浮点加法不满足结合律 ((a+b)+c ≠ a+(b+c)),所以不打开 -ffast-math 时
// 编译器**不允许**把这条链拆开 —— 它只能老老实实按你写的顺序算。
// 本框架的编译选项钉死为 -O3 -march=native,刻意不含 -ffast-math。

#include "ctx.h"

void sum_reduce(Ctx& ctx) {
    const int64_t n = (int64_t)ctx.n;

    double s = 0.0;
    for (int64_t i = 0; i < n; ++i) {
        s += (double)ctx.x[i];
    }

    ctx.out[0] = s;
}
