//
// 唯一的规则:只能改这个函数体。
//   - 不能改函数签名(框架按 void sum_reduce(Ctx&) 调用)
//   - 不能改编译选项(框架钉死 -O3 -march=native,刻意不开 -ffast-math)
//   - 可以加辅助函数、可以写 intrinsics,但计时只覆盖这个函数的调用
//
// 满分(参考解)能跑到 5.6x 以上。题面里写了完整的思路,这里只给一个起点。
// ============================================================================

#include "ctx.h"

void sum_reduce(Ctx& ctx) {
    const int64_t n = (int64_t)ctx.n;

    // TODO: 这个循环哪里慢?
    //
    // 先别看代码,想一想:它做了 n 次加法,每次加法读 4 个字节。
    // 16MB 数据在这台机器上顺序读一遍只要 ~0.7ms,而它跑了 4.1ms ——
    // 所以**问题不在带宽**。那时间花在哪了?
    //
    // 提示:画出这一行代码的**数据依赖图**。
    //   s += x[i] 用到的 s,正是 s += x[i-1] 算出来的那个 s。
    //   那么第 i 次加法最早能在什么时候开始?第 i+1 次呢?
    //
    // 再提示:查一下浮点加法(vaddsd)的延迟和吞吐。
    //   如果这些加法能并行起来,理论上限是多少?现在离它有多远?
    //   延迟 ÷ 吞吐 = 需要几条独立的链才能填满流水线?
    //
    // 改完这个之后**别急着交** —— 你会发现加速比停在某个数字上不动了,
    // 而且再加累加器也没用。那时候瓶颈已经换了地方,去题面里看第二幕。
    //
    // 两个必须注意的地方:
    //
    // 1) 收尾。展开成 k 路之后 n 不一定被 k 整除。odd 用例的 n=1000003
    //    不是 2 的幂,漏掉余数在 big/tiny 上完全看不出来,只有它会抓住你。
    //
    // 2) 不要顺手把 double 改成 float。实测串行的 float 累加**同时**踩两个坑:
    //    速度还是 1.00x(float 加法的延迟和 double 一样),而且 big 用例判错 ——
    //    和约 2.1e6,float 在这个量级上相邻可表示数间隔 0.125,4M 次累积的
    //    舍入误差远超本题允许的 21。必须保持 double。
    //    (有意思的是:如果你已经拆成了多路,float 反而不一定错 ——
    //     链短了,误差也小。但既然 float 一点不比 double 快,就没必要冒这个险。)

    double s = 0.0;
    for (int64_t i = 0; i < n; ++i) {
        s += (double)ctx.x[i];
    }

    ctx.out[0] = s;
}
