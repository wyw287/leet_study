// 题目 07 的参考解:共享内存私有化(privatization)。
//
// 这道题只有**一个**关键洞察,剩下都是围绕它的工程细节:
//
//   朴素实现慢,不是因为要读的数据多(读一遍 128MB 在 4090 上只要一百多 µs),
//   而是因为 3300 万次原子加挤在 100 个地址上,而 L2 对同一个地址的原子操作
//   是**串行**的。瓶颈在原子单元,不在显存 —— 数据早就读完了,加不完。
//
//   所以:让每个块先在**共享内存**里累加,最后只把 (块数 × 桶数) 次加法
//   并到全局。冲突没有消失,它被搬到了一个延迟低一个数量级、
//   而且 128 个 SM 各自独立的地方。
//
// 实测(2026-09-25,4090,框架自动清 L2,big 用例 n=33554432):
//     朴素基线(全局原子加)      ~6.2 ms      ~22 GB/s     ~2% 峰值
//     本参考解(4096 块)         0.146 ms     917 GB/s     91% 峰值
//
// 一个值得注意的事实:私有化之后,块数从 4096 降到 128(每 SM 一块)
// 只掉 1 个百分点(91% → 90%),而降到 64 块会掉到 71%、32 块掉到 40%。
// 也就是说冲突解决掉之后,瓶颈立刻换成了「并行度有没有铺满 128 个 SM」——
// 这道题从「原子冲突题」退化成了一道普通的访存题,剩下的空间在硬件上。

#include "ctx.h"

#define HIST_BLOCK 256

__global__ void histogram(const int* __restrict__ data,
                          int* __restrict__ bins,
                          int n, int nbins) {
    extern __shared__ int sh[];

    // ---- 第一步:块内私有直方图清零 ----
    // 每个块一份,块内所有线程协作清零。这里的清零和「清 bins」是两件事:
    // 共享内存是新拿到的、内容未定义,所以**必须**先清;
    // 而 bins 的清零在 launcher 里(见下)。
    for (int i = threadIdx.x; i < nbins; i += blockDim.x) {
        sh[i] = 0;
    }
    // 这一处 __syncthreads 不能省:否则先跑到下面的线程会往还没清完的
    // 共享直方图里加数,那些计数随后被清零吃掉。
    __syncthreads();

    // ---- 第二步:块内累加(grid-stride)----
    // 用 grid-stride 而不是「一个线程一个元素」:块数不需要覆盖全部元素,
    // n 不整除线程总数时也天然没有尾巴问题。
    //
    // 这一步的 atomicAdd 打在**共享内存**上:在 SM 内部完成,冲突只在块内排队,
    // 而不是全卡排在同一条 L2 队列上。
    const int stride = gridDim.x * blockDim.x;
    for (int i = blockIdx.x * blockDim.x + threadIdx.x; i < n; i += stride) {
        int v = data[i];
        if (v >= 0 && v < nbins) {
            atomicAdd(&sh[v], 1);
        }
    }
    // 这一处 __syncthreads 同样不能省:没有它,某些线程会把还只加了一半的
    // 共享直方图并到全局去 —— 结果偏小,而且每次跑可能不一样(竞态)。
    // 这正是 racecheck 要抓的东西,也是 verify.repeat 存在的理由。
    __syncthreads();

    // ---- 第三步:块内结果并到全局 ----
    // 全局原子加的次数:(块数 × nbins),而不是 n。
    // 块数 4096、nbins 128 时是 52 万次,比 3355 万次少 64 倍 —— 而且这 52 万次
    // 是分散在 100 个有数据的桶上的,每个桶约 5000 次,不是 33 万次。
    //
    // `if (sh[i])` 不是必须的,但它跳过空桶那一次没意义的原子加。
    // 本题数据只落在 0..99,128 个桶里有 28 个必然是空的。
    for (int i = threadIdx.x; i < nbins; i += blockDim.x) {
        if (sh[i]) {
            atomicAdd(&bins[i], sh[i]);
        }
    }
}

void histogram_launch(LaunchCtx& ctx) {
    // ---- (a) bins 必须先清零 ----
    // bins 是 out 缓冲,框架在每次执行前会把它填成毒值 0x5EED5EED,
    // 用来精确识别「kernel 根本没写输出」。累加型输出不清零的话,
    // 结果是「毒值 + 计数」,稳定地错。
    //
    // 这里**不能**在 kernel 里清:`if (threadIdx.x < nbins) bins[...] = 0;`
    // 加 __syncthreads() 只保证**块内**顺序,别的块可能已经开始加了。
    // 跨块顺序需要 grid sync 或者多一次 kernel 启动,这里用最省事的
    // cudaMemsetAsync(512 字节,约 1µs,相对 146µs 的 kernel 可以忽略)。
    cudaMemsetAsync(ctx.bins, 0, sizeof(int) * (size_t)ctx.nbins, ctx.stream);

    // ---- (b) 块数:这里有个真实的取舍,而且答案是"给足" ----
    // 实测这一档(4090,big 用例):
    //     32 块 → 40%    64 块 → 71%    128 块 → 90%    4096 块 → 91%
    // 128 是 SM 的个数,也是这条曲线的拐点 —— 低于它就有 SM 在闲着。
    // 再往上加收益只有 1%,但归并阶段的全局原子加次数 = 块数 × nbins
    // 会跟着涨,所以也不必开到几万块。
    // 4096 是实测的甜点区;这里顺手压了个上限,免得小用例上开几千个块
    // 去干几万个元素的活(那样固定开销反而占大头)。
    int block = HIST_BLOCK;
    int want = (ctx.n + block - 1) / block;
    int grid = want < 4096 ? want : 4096;

    // ---- (c) 共享内存大小作为第三个启动参数传进去 ----
    // nbins 个 int = 512 字节,对 occupancy 没有影响。
    histogram<<<grid, block, sizeof(int) * (size_t)ctx.nbins, ctx.stream>>>(
        ctx.data, ctx.bins, ctx.n, ctx.nbins);
}

