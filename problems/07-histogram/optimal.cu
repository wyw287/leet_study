// 还想再往上压?下面两条都真实存在,但这道题上收益都有限 —— 原因是
// 91% 已经接近「读」这条通路的实际上限了。
//
// 1. **int4 向量化读。** 一个线程一次搬 16 字节、做 4 次共享原子加,
//    访存指令数降到 1/4。实测 4096 块下从 917 GB/s 到 930 GB/s(+1.4%),
//    **在噪声量级** —— 说明瓶颈确实已经不是指令吞吐了。
//    但如果你卡在 60%~70% 那一档(块数不够、SM 闲着),向量化也救不了你:
//    那一档缺的是并行度,不是指令数。先看块数,再看向量化。
//    注意 ragged 用例的 n = 16777259 不是 4 的倍数:主体用 int4 循环,
//    剩下的 n % 4 个元素得单独用标量补一遍。
//
// 2. **子直方图(降 bank 冲突)。** 共享内存 32 个 bank,桶 v 落在 bank v%32。
//    随机数据下平均每个 bank 会撞上好几个线程,同 bank 的原子加也要排队。
//    给每个线程分一份子直方图(用 threadIdx.x % K 选),并把步长写成
//    **nbins + 1** 而不是 nbins —— 这一步是关键:128 是 32 的倍数,
//    用 nbins 做步长的话,所有子直方图的第 v 个桶还是落在同一个 bank 上,
//    等于白分。加 1 之后 bank 变成 (sub*(nbins+1) + v) % 32,才真正错开。
//    本题上收益在噪声量级(瓶颈早就不在共享内存了)。
//    它的价值在于:当桶更少(比如 8 个)、冲突更极端时,它是救命的。
