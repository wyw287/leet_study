// 题目 07:直方图统计
//
//   bins[v] = data 里值等于 v 的元素个数      (v = 0 .. nbins-1)
//
// 只在本文件里写代码。device 内存的分配、数据搬运、计时、校验、越界检测
// 都由框架完成 —— 你只需要写 kernel 和决定启动配置。
//
//   ctx.data   const int*  device 指针,长度 ctx.n,每个元素在 0..99 之间
//   ctx.bins   int*        device 指针,长度 ctx.nbins(=128),需要你写入
//   ctx.n      int         元素个数
//   ctx.nbins  int         桶的个数(=128),比 100 大
//
// 基线(每个元素一次全局原子加)是**完全正确**的。你的任务不是「让它对」,
// 而是**让它快** —— 这题和 01/02/03 不一样,朴素写法离带宽天花板差了 40 倍,
// 所以有真实的优化空间。
//
// ---------------------------------------------------------------------------
// 先算清楚基线为什么慢 —— 这道题的全部内容都在这个算式里
// ---------------------------------------------------------------------------
// 一次 `atomicAdd(&bins[v], 1)` 落在哪个地址,由**数据**决定。同一 warp 的
// 32 个线程各读各的 v,地址是散的,没法合并 —— 这是「散射写」。
//
// 更糟的是:**同一个地址的原子操作在 L2 里是串行的**。数据只落在 0..99,
// 也就是 100 个桶,3300 万个元素平均每个桶要被加 **33 万次**。就算这 100 个桶
// 分属不同的 L2 slice、彼此完全并行,每个桶那条 33 万次长的串行链也要走完。
//
// 结果是:读一遍 128MB 只要约 130µs,而基线要跑 **6.2ms** —— 慢了 40 多倍,
// 而且慢的原因和带宽毫无关系:数据早就读完了,是加不完。
//
// 所以修法的方向不是「少读」,而是**「把冲突搬到一个更便宜的地方去」**。
//
// ---------------------------------------------------------------------------
// 1) 写 kernel
// ---------------------------------------------------------------------------
__global__ void histogram(const int* __restrict__ data,
                          int* __restrict__ bins,
                          int n, int nbins) {
    // TODO: 共享内存私有化(privatization)。三步:
    //
    // ── 第一步:每个块在共享内存里放一份**自己的**直方图 ──────────────
    //   extern __shared__ int sh[];          // 大小由启动配置传入
    //   for (int i = threadIdx.x; i < nbins; i += blockDim.x) sh[i] = 0;
    //   __syncthreads();                     // ← 为什么必须有?
    //
    // 这一步把「100 个全局地址」变成「每个块一份、128 个片上地址」。
    // 共享内存的原子加在 SM 内部完成,延迟二三十个 cycle,而且 128 个 SM
    // 各自独立 —— 冲突从「全卡排一条队」变成「每个 SM 排自己的队」。
    //
    // ── 第二步:块内累加 ────────────────────────────────────────────────
    //   for (int i = blockIdx.x * blockDim.x + threadIdx.x; i < n; i += stride) {
    //       int v = data[i];
    //       if (v >= 0 && v < nbins) atomicAdd(&sh[v], 1);
    //   }
    //   __syncthreads();                     // ← 这一处漏了会怎样?
    //
    // 注意循环写成 **grid-stride**(i += gridDim.x * blockDim.x),不是
    // `if (i < n)`。块数不必覆盖全部元素,而且 n 不整除时不用单独处理尾巴。
    //
    // ── 第三步:把块内的结果并到全局 ────────────────────────────────────
    //   for (int i = threadIdx.x; i < nbins; i += blockDim.x)
    //       if (sh[i]) atomicAdd(&bins[i], sh[i]);
    //
    // 全局原子加的次数从 n 次降到 (块数 × nbins) 次 —— 这才是量级上的胜利。
    // `if (sh[i])` 不是必须的,但它省掉了「落不到数据的桶」那次没用的原子加;
    // 本题 nbins=128 而数据只落在 0..99,有 28 个桶一定是空的。
    //
    // ── 两个容易踩的坑 ──────────────────────────────────────────────────
    // * **bins 必须先清零。** 框架在每次执行前把 out 缓冲填成毒值
    //   0x5EED5EED,累加型输出不清零的话,结果是「毒值 + 计数」。
    //   清零在 launcher 里做(见下面第 2 步),不要在 kernel 里用
    //   `if (tid < nbins) bins[tid] = 0; __syncthreads();` 糊弄 ——
    //   __syncthreads 只同步**一个块**,别的块可能早就加完了。
    //   本题 100..127 号桶一个数都不会落进去,它们会一直是 0 ——
    //   所以「忘了清零」在这道题里是藏不住的。
    // * **bank 冲突。** 共享内存 32 个 bank,地址 v 落在 bank (v % 32) 上。
    //   128 个桶正好占满 4 轮,随机访问下平均每个 bank 会撞上好几个线程,
    //   而同一个 bank 的原子加也是要排队的。真到了瓶颈可以给每个线程
    //   分一份**子直方图**(用 threadIdx.x % K 选),并且把子直方图的
    //   步长写成 nbins+1 而不是 nbins —— 让不同子直方图的同一个桶落到
    //   不同 bank 上。这一步能拿多少,自己测:可能很值,也可能在噪声里。
    //
    // 卡住了先看 `leet solution 07`,那里有一份能跑到参考评级的实现。
}

