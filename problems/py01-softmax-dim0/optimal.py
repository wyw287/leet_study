"""题目 py01 的参考解 —— 让归约落在 PyTorch 能高效处理的维度上

实测(8192×8192):
    基线 torch.softmax(x, dim=0)       6.85 ms   (有效带宽  78 GB/s)
    本实现                             2.08 ms   → 3.30x (约 518 GB/s 实际流量)
    tall 用例(32768×2048)            26.31 ms → 2.02 ms  → 13.05x

关键认知只有一句:**让归约维成为访存最快的那一维**。

但要注意一个反直觉的细节:这里**不需要**显式调用 .contiguous()。
PyTorch 的 TensorIterator 会在内部判断哪种访问模式更快并自行重排 ——
实测「带 .contiguous()」与「不带」的耗时分别是 2.065 ms 和 2.063 ms,
在测量噪声以内。

所以真正的心智模型不是"我要手动转置",而是
"我要让归约发生在 PyTorch 能高效处理的那个维度上"。
"""

import torch


def forward(ctx):
    # x.t() 是零成本的**视图**(只改 strides,不搬数据),
    # 但它让归约维从 dim=0 变成了 dim=1 —— 这才是起作用的那一步。
    # 最后再 .t() 回原布局,同样零成本。
    return torch.softmax(ctx.x.t(), dim=1).t()


# ---------------------------------------------------------------------------
# 两个对照实现,用来理解为什么这样写
#
# 【反例 1】只 .t() 不换维度 —— 等于什么都没做:
#
#     return torch.softmax(ctx.x.t(), dim=0).t()
#
#   x.t() 的形状是 (cols, rows),沿它的 dim=0 归约 = 沿原 x 的 dim=1,
#   而 dim=1 本来就是连续的 —— 但那样算出来的根本不是列方向 softmax。
#
# 【反例 2】自己用 max/exp/sum/div 展开 —— 实测只有 1.80x:
#
#     xt = ctx.x.t().contiguous()
#     m  = xt.max(dim=1, keepdim=True).values
#     e  = (xt - m).exp()
#     return (e / e.sum(dim=1, keepdim=True)).t()
#
#   每一步都会**物化一个完整的中间张量**(e 就是 268MB),访存遍数从 2 遍
#   涨到 6 遍以上。而 torch.softmax 是融合过的单次内核 ——
#   数值稳定的事交给它做,不要重新发明。
#
# 【反例 3】往预分配的 ctx.out 里 copy_ —— 实测只有 1.87x:
#
#     ctx.out.copy_(torch.softmax(ctx.x.t(), dim=1).t())
#
#   多一次全量拷贝(读 268MB + 写 268MB)。直接 return 更快,
#   在访存瓶颈题上这笔账很显眼。
#
# ---------------------------------------------------------------------------
# 还有多少空间?
#
# 现在 2.02 ms,对应约 2 遍访存。理论上如果能把 max 减法、exp、求和、除法
# **融合进一个内核**,只需要读一遍 x、写一遍 out —— 下限大约 0.6 ms。
# 那 3 倍多的差距,就是从"会用 PyTorch"到"会写 kernel"的那道门。
# ---------------------------------------------------------------------------
