                            float* __restrict__ part,
                            int n, int nblk) {
    // TODO: 你打算在这里做什么?先想清楚,再写。
    //
    // 几个已经在 04/10 里学过、这里要再用一遍的东西:
    //
    //   * 跨步循环 `for (i = beg + t; i < end; i += BLOCK)`:让同一个 warp 的
    //     32 个线程地址连续。你要扫的那一段长 32768,远大于 BLOCK,
    //     所以是个"tile 一个 tile 走"的循环。
    //
    //   * 块内树形归约(04):把一个 block 里各线程的局部和合并成一个数。
    //
    //   * 块内扫描(10):把 BLOCK 个值变成它们的 inclusive 前缀和。
    //
    //   * **进位(carry)**:tile 之间是有序的 —— 第 k 个 tile 里每个元素的
    //     前缀和,都要加上前 k-1 个 tile 的总和。这个进位跨了 tile,
    //     也就跨了 __syncthreads 的边界。块内扫描本身不产生它,
    //     你得自己把它接上:
    //
    //         carry = 本段的块间偏移;
    //         for (每个 tile) {
    //             把 tile 搬进共享内存(越界补 0);
    //             __syncthreads();
    //             块内 inclusive 扫描;
    //             last = sm[BLOCK-1];       // 本 tile 的总和
    //             __syncthreads();          // ← 为什么这道屏障不能省,见下
    //             if (在界内) y[i] = sm[t] + carry;
    //             carry += last;
    //         }
    //
    //   * 越界补 0 不只是为了"不写坏内存":补 0 之后 sm[BLOCK-1] 天然等于
    //     **本 tile 有效元素之和**,尾巴那一段不用额外判断。
    //
    // ---- 最容易错的一处 -------------------------------------------------
    //   那个"读完 last 之后的 __syncthreads()"为什么不能省:
    //     last 是**所有线程**都要读的同一个槽位(sm[BLOCK-1])。少了这道屏障,
    //     持有最后一个槽位的那个线程可能已经进入下一轮、把它覆盖成本 tile
    //     的第一个元素,而别的线程才刚开始读 —— 进位就错了。而且错得很隐蔽:
    //     只在特定调度下错,repeat=1 时未必复现。
    //   一轮里其实有三处同步需求,别把它们合并:
    //     ① 写 sm → 开始扫描      (扫的必须是本 tile 的数据)
    //     ② 扫描结束 → 读 last
    //     ③ 读完 last → 下轮写 sm (别人才敢覆盖)
    // ---------------------------------------------------------------------
    (void)x; (void)y; (void)part; (void)n; (void)nblk;
}

