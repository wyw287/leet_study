// 题目 11:全局前缀和(跨块扫描)
//
// 只在本文件里写代码。device 内存的分配、数据搬运、计时、校验、越界检测
// 都由框架完成 —— 你只需要写 kernel 和决定启动配置。
//
// 语义:长度 n 的数组,输出它的 **inclusive** 前缀和
//
//     y[0] = x[0]
//     y[i] = y[i-1] + x[i]          (i > 0)
//
//   ctx.x     const float*  device 指针,长度 n(x 的每个元素都在 (0,1])
//   ctx.y     float*        device 指针,长度 n,需要你写入
//   ctx.part  float*        device 指针,长度 n —— scratch,随你怎么用
//   ctx.n     int           元素个数
//   ctx.nblk  int           题目规定的块数(= 段数)
//
// 分段约定(必须遵守,否则和参考解对不上):
//     第 b 个块负责 [b*CH, min(n, (b+1)*CH)),CH = ceil(n / nblk)
//
// 提醒:scratch 缓冲在每次校验前会被框架填成毒值(NaN),用之前必须自己写。
// 提醒:nblk 不超过 1024(所有用例都满足)。
//
// 这道题和 10 题的关系:
//   10 题教你"把一条依赖链拆开,让一个 block 内的线程协作"。
//   那道题的一行只有 1024 个元素,一个 block 装得下 —— 块内就够了。
//   现在整个数组是**一条**链,3200 万个元素,一个 block 装不下,必须跨块。
//
//   **而 CUDA 里块与块之间没有任何同步原语**:你没法让块 5 等块 4 算完。
//   能等的只有两样东西:① kernel 边界;② 原子操作 + 自己写的 flag/计数。
//
//   这道题唯一的新知识点就是这句话。剩下的都是你已经会的:
//   块内归约(04)、块内扫描(10)、合并访存(01)。
//
// 骨架只给了一个 kernel 名字。**你可以在这个文件里定义任意多个 kernel** ——
// 到底需要几个、怎么分工,正是这道题要你想清楚的事。

