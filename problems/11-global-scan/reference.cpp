// 题目 11 的参考解(CPU,ground truth)—— 不暴露给做题者。
//
// 一个标量循环:维护一个累加器,每读一个数就"先加再写"。
// inclusive 前缀和的语义就是这样,直白到没有出错的空间。
//
// 为什么累加器用 double:
//   本题的输入全是正数(x ∈ (0,1]),整个数组的和约 1670 万。
//   用 float 累加的话,走到数组末尾时单次加法的舍入就有 1 的量级
//   (f32 在 1.6e7 附近的 ulp 是 2),参考解自己就带上了可观的误差 ——
//   那"对拍不过"就分不清是选手错了还是它自己不准。
//   double 累加把误差压到相对 1e-8 量级,再转成 float 写出,可以当作真值。
//
// 边界情况说明:从头扫到尾,不依赖任何整除关系 ——
// n 是质数、不是 2 的幂、nblk 不整除 n,对参考解都没有区别
// (它压根不关心分段是怎么切的)。

#include "ctx.h"

void reference(RefCtx& ctx) {
    double acc = 0.0;
    for (int i = 0; i < ctx.n; ++i) {
        acc += (double)ctx.x[i];
        ctx.y[i] = (float)acc;
    }
}
