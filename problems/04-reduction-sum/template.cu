// 题目 04:归约求和
//
// 把 n 个 float 全部加起来,输出**一个** float。
//
//   ctx.input   const float*  device 指针,长度 n
//   ctx.output  float*        device 指针,**只有 1 个元素**(shape 是空的)
//   ctx.n       元素个数
//
// 注意 output 是标量:整个 kernel 里只有一个线程应该写它。

#include "ctx.h"

// ---------------------------------------------------------------------------
// 1) 写 kernel
// ---------------------------------------------------------------------------
__global__ void reduce_sum(const float* input, float* output, int n) {
    // 单块版本(基线就是这么写的)是能跑对的,但只用了 1/128 的算力。
    // 目标是多线程块 + 两级归约:
    //
    //   第一级(块内):
    //     float sum = 0.f;
    //     for (int i = tid; i < n; i += blockDim.x * gridDim.x) sum += input[i];
    //     // 跨步访问让全局读保持合并
    //
    //     // 32 个线程一个 warp,用 __shfl_down_sync 做 warp 内归约,
    //     // 不需要共享内存也不消耗同步:
    //     for (int off = 16; off > 0; off >>= 1)
    //         sum += __shfl_down_sync(0xffffffff, sum, off);
    //     // 此时每个 warp 的第 0 号线程持有本 warp 的部分和
    //
    //     // 每个 warp 的结果写进共享内存数组,再对一个 32 元素的数组做一次
    //     // warp 内归约即可,省掉 log2(1024)=10 轮 __syncthreads
    //
    //   第二级(块间):
    //     // 每个块把自己的部分和写到一块临时缓冲,再归约一次;
    //     // 或者用 atomicAdd 直接累加到 output(简单,但要注意:
    //     // output 必须先清零 —— 框架已经帮你填了毒值,所以你得自己写 0)
    //
    // 踩坑提示:
    //   * __shared__ 数组写完必须 __syncthreads() 才能被别的线程读。
    //     漏掉是最经典的竞态 bug,而且往往「有时对有时错」。
    //   * 两个线程同时 atomicAdd 到 output 是安全的;
    //     但如果你改成普通写 output[0] += ...,那就是竞态。
    //   * n 不整除线程总数时别漏最后的边界。
}

