// 题目 16 的参考解(CPU,ground truth)—— 不暴露给做题者。
//
// 语义:bit i(第 i>>5 个 word 的第 i&31 位,LSB 对应序号小的元素)= (x[i] > 0)。
//       word 里超出 n 的那些位必须是 0。
//
// 这是个**整数**输出,框架要求逐位精确相等 —— 没有容差可言。所以这里刻意写成
// 最直白的"先清零、再逐位置位":语义一眼可见,不会有边界上的含糊。
//
// 注意用的是 `> 0.0f` 而不是 `>= 0.0f`:输入是 [-1,1) 的 uniform,取到 0 的概率
// 极低,但"0 算正还是算负"必须在题面上钉死,否则 -0.0f / +0.0f 就是一场灾难。

#include "ctx.h"

void reference(RefCtx& ctx) {
    // 先清零:超出 n 的尾巴位靠这一步保证是 0。
    // (CUDA 侧的对应动作是 memset,或者"让每个 word 都被某一个线程完整覆盖"。)
    for (int w = 0; w < ctx.nw; ++w) {
        ctx.bits[w] = 0u;
    }
    for (int i = 0; i < ctx.n; ++i) {
        if (ctx.x[i] > 0.0f) {
            ctx.bits[i >> 5] |= (1u << (i & 31));
        }
    }
}
