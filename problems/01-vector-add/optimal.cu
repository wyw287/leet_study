// 题目 01 的参考解
//
// 这道题**没有优化空间**,所以这份"参考解"的重点不是技巧,而是让你看清
// 一个事实:最朴素的写法已经跑满显存带宽了。
//
// 实测(4090,框架自动清 L2):
//     n = 16,777,216  →  0.180 ms,有效带宽 1117 GB/s
//     4090 标称峰值           1008 GB/s
//
// 也就是说,这个 kernel 已经把带宽用到了标称上限(略超是因为事件停止计时的
// 瞬间,最后一批写还在 L2 里没落盘,少算了那部分流量)。
//
// 所以本题的"及格线"就是认识到:
//   **访存瓶颈题里,写对就行 —— 剩下的空间不在算法,在硬件。**

#include "ctx.h"

__global__ void vecadd(const float* a, const float* b, float* c, int n) {
    int i = blockIdx.x * blockDim.x + threadIdx.x;
    // 边界判断不能省:n 不整除线程总数时,最后一批线程会越界。
    // 框架的哨兵区会抓到它(报出往后越界了多少个元素)。
    if (i < n) {
        c[i] = a[i] + b[i];
    }
}

void vecadd_launch(LaunchCtx& ctx) {
    // 线程块大小的选择:256 与 512 通常都在最优点附近。
    // 太小(如 32)会让块的调度开销占比上升;太大(1024)会降低 occupancy
    // 的灵活性。这道题上 128~512 的差别在测量噪声以内 —— 可以自己扫一遍试试。
    int block = 256;
    int grid = (ctx.n + block - 1) / block;   // 向上取整
    vecadd<<<grid, block>>>(ctx.a, ctx.b, ctx.c, ctx.n);
}

// ---------------------------------------------------------------------------
// 值得亲手验证的两件事:
//
// 1. **向量化有用吗?** 用 float4 让每线程一次搬 16 字节:
//
//        __global__ void vecadd4(const float4* a, const float4* b, float4* c, int n4) {
//            int i = blockIdx.x * blockDim.x + threadIdx.x;
//            if (i < n4) c[i] = make_float4(a[i].x + b[i].x, a[i].y + b[i].y,
//                                          a[i].z + b[i].z, a[i].w + b[i].w);
//        }
//
//    它把指令数降到 1/4,但**带宽不会变** —— 带宽已经是瓶颈了。
//    你会看到耗时基本一样。这个实验的价值在于让你分清
//    「指令开销」和「带宽」什么时候是瓶颈。
//
// 2. **把下标写成跨步的会怎样?**
//
//        int i = threadIdx.x * gridDim.x + blockIdx.x;   // 故意的
//
//    带宽会掉到原来的几分之一。因为同一 warp 的相邻线程访问的地址不再相邻,
//    硬件没法把它们合并成少的显存事务 —— 这就是 coalescing 失效的样子。
