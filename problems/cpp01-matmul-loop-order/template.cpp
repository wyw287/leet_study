#include "ctx.h"

void matmul(Ctx& ctx) {
    const int n = ctx.n;

    // TODO: 这段代码哪里慢?
    //
    // 先别看代码,想一想:矩阵乘做了 n³ 次乘加,而数据只有 3n² 个。
    // 也就是说每个数据元素平均要被用到 n 次(=384 次),所以**理论上**
    // 访存应该完全可以被缓存吸收。既然如此,为什么它还是慢?
    //
    // 提示:盯着最内层循环那个 k,分别看它访问 A 和 B 的方式。
    //   同一个循环里,a[i][k] 和 b[k][j] 的访存模式一样吗?
    //   一个步长是多少?另一个呢?
    //
    // 想清楚之后,你会发现修复只需要动**一行** —— 把某两层循环换个位置。
    // 不要急着加 shared memory 或手写 SIMD:C 里的数据结构是扁平的,
    // 没有 CUDA 那种"小得可怜的 shared memory"约束,
    // 交换循环次序带来的收益往往比任何花哨手段都大。

    for (int i = 0; i < n; ++i) {
        for (int j = 0; j < n; ++j) {
            float s = 0.0f;
            for (int k = 0; k < n; ++k) {
                s += ctx.A[i * n + k] * ctx.B[k * n + j];
            }
            ctx.C[i * n + j] = s;
        }
    }
}
