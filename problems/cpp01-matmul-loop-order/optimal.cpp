// 参考解 —— 一份能达到 S 级的实现。卡住了再看。
//
// 唯一的改动:把最内层循环从 j 换成 k。就这么一点。
//
// 原来的三段循环 i → j → k,内层在 B 上跨步走(步长 n*4 字节),
// 每读 4 个字节就换一条 cache line。换成 i → k → j 之后:
//
//   A[i*n+k] —— 整个内层循环里是**同一个值**,寄存器里放着,只读一次
//   B[k*n+j] —— j 连续,顺序流式读,一条 cache line 用满 16 个 float
//   C[i*n+j] —— j 连续,顺序读写
//
// 三条流全部变成顺序访问,硬件预取器也能正常工作(跨步访问它猜不出来)。
// 实测:79.5ms → 4.0ms,约 20x。
//
// 一个容易踩的坑:这里**不能**只把 B 预先转置一份就来用。那要多一次
// n² 的读写(而且转置本身也要处理跨步访问),算下来不如直接换循环次序 ——
// 换序是零额外访存的。

#include "ctx.h"

void matmul(Ctx& ctx) {
    const int n = ctx.n;

    // C 要累加,所以先清零
    for (int i = 0; i < n; ++i) {
        for (int j = 0; j < n; ++j) {
            ctx.C[i * n + j] = 0.0f;
        }
    }

    for (int i = 0; i < n; ++i) {
        for (int k = 0; k < n; ++k) {
            // 提到循环外:内层跑一整个 j 循环,这个值都不变
            const float a = ctx.A[i * n + k];
            for (int j = 0; j < n; ++j) {
                ctx.C[i * n + j] += a * ctx.B[k * n + j];
            }
        }
    }
}
